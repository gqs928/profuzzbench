#!/usr/bin/env bash
set -euo pipefail

PREFLIGHT_ROOT="${PREFLIGHT_ROOT:-/work/results/preflight}"
OUT="${PREFLIGHT_OUT:-${PREFLIGHT_ROOT}/aflnet-60s-final9}"
mkdir -p "${PREFLIGHT_ROOT}"
bash /work/run.sh "${OUT}" "${PREFLIGHT_DURATION:-60s}"
test -s "${OUT}/aflnet-out/fuzzer_stats"
test -s "${OUT}/aflnet-out/ipsm.dot"
test -s "${OUT}/post-smoke/rtsp-smoke.json"
test -s "${OUT}/campaign/stop-status.txt"
test -s "${OUT}/post-smoke/stop-status.txt"
test -s "${OUT}/go-coverage.out"
test -s "${OUT}/go-coverage-summary.txt"
[[ "$(<"${OUT}/wrapper-exit-code.txt")" == 124 ]]
grep -qx 'graceful=yes' "${OUT}/campaign/stop-status.txt"
grep -qx 'process_exit_code=0' "${OUT}/campaign/stop-status.txt"
grep -qx 'graceful=yes' "${OUT}/post-smoke/stop-status.txt"
grep -qx 'process_exit_code=0' "${OUT}/post-smoke/stop-status.txt"
test -n "$(find "${OUT}/go-coverdata" -type f -name 'covcounters.*' -print -quit)"
test -n "$(find "${OUT}/post-smoke/go-coverdata" -type f -name 'covcounters.*' -print -quit)"
awk -F: '/^execs_done[[:space:]]*:/ { if ($2+0 > 0) ok=1 } END { exit !ok }' "${OUT}/aflnet-out/fuzzer_stats"
awk -F: '/^paths_total[[:space:]]*:/ { if ($2+0 > 1) ok=1 } END { exit !ok }' "${OUT}/aflnet-out/fuzzer_stats"
grep -Eq '^[[:space:]]*[1-5][0-9]{2}[[:space:]]*\[' "${OUT}/aflnet-out/ipsm.dot"
grep -q -- ' -> ' "${OUT}/aflnet-out/ipsm.dot"
awk '/^total:/ { x=$NF; sub(/%$/, "", x); if (x+0 > 0) ok=1 } END { exit !ok }' "${OUT}/go-coverage-summary.txt"
cp /work/build-evidence/build-lock.txt "${PREFLIGHT_ROOT}/.build-lock.txt.new"
mv -f "${PREFLIGHT_ROOT}/.build-lock.txt.new" "${PREFLIGHT_ROOT}/build-lock.txt"
cp /work/build-evidence/go-version-info.txt "${PREFLIGHT_ROOT}/.go-version-info.txt.new"
mv -f "${PREFLIGHT_ROOT}/.go-version-info.txt.new" "${PREFLIGHT_ROOT}/go-version-info.txt"
SUMS_TMP="${PREFLIGHT_ROOT}/.SHA256SUMS.new.$$"
(cd "${PREFLIGHT_ROOT}" && find . -type f ! -name SHA256SUMS ! -name '.SHA256SUMS.new.*' -print0 | sort -z | xargs -0 sha256sum > "${SUMS_TMP}")
mv -f "${SUMS_TMP}" "${PREFLIGHT_ROOT}/SHA256SUMS"
echo "PASS: RTSP/TCP response-state preflight, graceful campaign and fresh post-campaign publisher/reader services, and merged Go native coverage; evidence=${OUT}"
